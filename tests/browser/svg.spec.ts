import { readFileSync } from "node:fs";
import { expect, test, type Page } from "@playwright/test";

// Real-browser proof for @dusrel/image-svg: the self-contained
// fixture bundle (the package + SVGO's browser build, built by the
// package's second tsdown config) optimises real SVGs in all
// three engines, and the browser itself still renders the result.
const fixtureBundle = readFileSync(
  new URL("../../packages/features/svg/test/.fixture/browser-fixture.js", import.meta.url),
  "utf8",
);

async function loadFixture(page: Page) {
  await page.evaluate((bundle) => {
    const url = URL.createObjectURL(new Blob([bundle], { type: "text/javascript" }));
    return import(url);
  }, fixtureBundle);
}

test.beforeEach(async ({ page }) => {
  await page.goto("about:blank");
  await loadFixture(page);
});

const BLOATED = `<?xml version="1.0" encoding="UTF-8"?>
<!-- generated by a design tool -->
<svg xmlns="http://www.w3.org/2000/svg" width="100" height="100">
  <g id="layer-one">
    <rect id="hero-rect" x="0" y="0" width="100.000" height="100" fill="#ff0000"/>
  </g>
</svg>`;

test("svg optimize: comments stripped, file shrinks, browser renders the result", async ({
  page,
}) => {
  const r = await page.evaluate(async (input) => {
    const { __svg: svg } = window as unknown as {
      __svg: typeof import("../../packages/features/svg/src/index.js");
    };
    const result = svg.optimizeSvgWithStats(input);
    // The browser itself must still render the optimised file.
    const bitmap = await createImageBitmap(new Blob([result.svg], { type: "image/svg+xml" }));
    return { ...result, svgText: result.svg, bitmapWidth: bitmap.width };
  }, BLOATED);
  expect(r.svgText).not.toContain("<!--");
  expect(r.outputBytes).toBeLessThan(r.originalBytes);
  expect(r.savingsRatio).toBeGreaterThan(0);
  expect(r.bitmapWidth).toBe(100);
});

test("svg optimize: preserveIds keeps ids referenced from CSS/JS", async ({ page }) => {
  const r = await page.evaluate((input) => {
    const { __svg: svg } = window as unknown as {
      __svg: typeof import("../../packages/features/svg/src/index.js");
    };
    return svg.optimizeSvg(input, { preserveIds: true });
  }, BLOATED);
  expect(r).toContain('id="hero-rect"');
  expect(r).toContain('id="layer-one"');
});

test("svg optimize: empty input is rejected", async ({ page }) => {
  const r = await page.evaluate(() => {
    const { __svg: svg } = window as unknown as {
      __svg: typeof import("../../packages/features/svg/src/index.js");
    };
    try {
      svg.optimizeSvg("   ");
      return "";
    } catch (e) {
      return (e as Error).message;
    }
  });
  expect(r).toContain("non-empty SVG string");
});
